"""
Run real-data benchmarks for the SS-NFPSO Q1 pipeline.

This script creates a unified real-data metrics table containing:
1. leakage-aware forecasting baselines on the local real revenue CSV; and
2. NFPSO metrics imported from, or generated by, `run_nfpso_experiments.py`.

Main output
-----------
    outputs/q1_minimal/real_data_benchmarks/metrics.csv
    outputs/q1_minimal/real_data_benchmarks/predictions.csv
    outputs/q1_minimal/real_data_benchmarks/manifest.csv

Why this script matters
-----------------------
`run_statistical_tests.py` needs a common long-form table:

    dataset, model, rmse, mae, smape_percent, mase, ...

This script makes the baseline and NFPSO rows use the same real-data condition
name, so they can be summarized and compared consistently.

Important scientific note
-------------------------
A single real series is not enough for strong statistical significance claims.
Use this script for the real-data benchmark table. Use synthetic and multi-series
runs for stronger paired statistical evidence.

Examples
--------
Quick run with simple baselines and existing NFPSO metrics:

    py run_real_data_benchmarks.py --quick --csv data\\tax_revenues.csv

Run only baselines:

    py run_real_data_benchmarks.py --nfpso-source skip

Run fresh quick NFPSO inside this script:

    py run_real_data_benchmarks.py --quick --nfpso-source run --csv data\\tax_revenues.csv

Then run statistics:

    py run_statistical_tests.py --inputs outputs/q1_minimal/real_data_benchmarks/metrics.csv --reference-model projected_constricted_nfpso --quick
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

import pandas as pd


ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from nfpsosc.baselines import BaselineResult, run_baseline
from nfpsosc.experiment import ExperimentConfig, run_experiment


DEFAULT_CONFIG = ROOT / "configs" / "q1_minimal_experiments.json"
DEFAULT_CSV = ROOT / "data" / "tax_revenues.csv"
DEFAULT_NFPSO_METRICS = ROOT / "outputs" / "q1_minimal" / "nfpso_experiments" / "metrics.csv"
DEFAULT_NFPSO_PREDICTIONS = ROOT / "outputs" / "q1_minimal" / "nfpso_experiments" / "predictions.csv"

DEFAULT_BASELINES = ["naive_1", "seasonal_naive", "drift"]
DEFAULT_QUICK_BASELINES = ["naive_1", "drift"]


def load_json(path: Path) -> Dict[str, Any]:
    """Load JSON config if available."""

    if not path.exists():
        print(f"[WARN] config not found, using defaults: {path}")
        return {}
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def ensure_dir(path: Path) -> Path:
    """Create and return a directory."""

    path.mkdir(parents=True, exist_ok=True)
    return path


def parse_csv_list(value: Optional[str]) -> Optional[List[str]]:
    """Parse comma-separated strings."""

    if value is None or value.strip() == "":
        return None
    return [item.strip() for item in value.split(",") if item.strip()]


def parse_float_list(value: Optional[str]) -> Optional[List[float]]:
    """Parse comma-separated floats."""

    items = parse_csv_list(value)
    if items is None:
        return None
    return [float(item) for item in items]


def parse_int_list(value: Optional[str]) -> Optional[List[int]]:
    """Parse comma-separated integers."""

    items = parse_csv_list(value)
    if items is None:
        return None
    return [int(item) for item in items]


def relpath(path: Path) -> str:
    """Return path relative to repository root when possible."""

    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def detect_value_column(df: pd.DataFrame, requested: Optional[str]) -> str:
    """Detect the numeric target column."""

    if requested:
        if requested not in df.columns:
            raise ValueError(f"Requested value column not found: {requested}")
        return requested

    candidates = [
        "revenue_million_yer",
        "value",
        "revenue",
        "tax_revenue",
        "amount",
        "y",
    ]
    for col in candidates:
        if col in df.columns:
            return col

    numeric_cols = []
    for col in df.columns:
        values = pd.to_numeric(df[col], errors="coerce")
        if values.notna().sum() >= 10:
            numeric_cols.append(col)

    if not numeric_cols:
        raise ValueError("Could not detect a numeric value column.")

    return numeric_cols[0]


def detect_date_column(df: pd.DataFrame, requested: Optional[str]) -> Optional[str]:
    """Detect the date/time column if available."""

    if requested:
        if requested not in df.columns:
            raise ValueError(f"Requested date column not found: {requested}")
        return requested

    for col in ["date", "month", "period", "time", "ds"]:
        if col in df.columns:
            return col

    return None


def load_real_series(
    csv_path: Path,
    value_column: Optional[str] = None,
    date_column: Optional[str] = None,
) -> pd.DataFrame:
    """Load and clean the real data series."""

    if not csv_path.exists():
        raise FileNotFoundError(f"CSV not found: {csv_path}")

    df = pd.read_csv(csv_path)
    if df.empty:
        raise ValueError(f"CSV is empty: {csv_path}")

    value_col = detect_value_column(df, value_column)
    date_col = detect_date_column(df, date_column)

    out = pd.DataFrame()
    if date_col:
        out["date"] = df[date_col]
        parsed_dates = pd.to_datetime(out["date"], errors="coerce")
        if parsed_dates.notna().sum() >= max(3, len(out) // 2):
            out["_sort_date"] = parsed_dates
    else:
        out["date"] = range(len(df))

    out["value"] = pd.to_numeric(df[value_col], errors="coerce")
    out = out.dropna(subset=["value"]).reset_index(drop=True)

    if "_sort_date" in out.columns:
        out = out.sort_values("_sort_date").drop(columns=["_sort_date"]).reset_index(drop=True)

    if len(out) < 20:
        raise ValueError(f"Series too short after cleaning: {len(out)} observations.")

    return out


def resolve_baselines(config: Dict[str, Any], cli_models: Optional[List[str]], quick: bool) -> List[str]:
    """Resolve baseline model names."""

    if cli_models is not None:
        return cli_models

    if quick:
        return DEFAULT_QUICK_BASELINES

    configured = config.get("models", [])
    excluded = {"legacy_nfpso", "projected_constricted_nfpso"}
    baselines = [m for m in configured if m not in excluded]
    return baselines or DEFAULT_BASELINES


def run_baseline_model(
    series: Sequence[float],
    dataset_name: str,
    model: str,
    n_lags: int,
    season_length: int,
    train_fraction: float,
    initial_train_size: Optional[int],
) -> tuple[Dict[str, Any], Optional[pd.DataFrame]]:
    """Run one baseline model and return a metrics row plus predictions."""

    print(f"[BASELINE] dataset={dataset_name} model={model}")
    start = time.perf_counter()
    status = "ok"
    error = None
    result: Optional[BaselineResult] = None

    try:
        kwargs: Dict[str, Any] = {}
        if model == "arima":
            kwargs["order"] = (1, 1, 0)
        elif model == "ets":
            kwargs["trend"] = "add"
            kwargs["seasonal"] = "add" if season_length > 1 else None
        elif model == "svr":
            kwargs.update({"C": 10.0, "epsilon": 0.05, "gamma": "scale"})
        elif model == "xgboost":
            kwargs.update({"n_estimators": 100, "max_depth": 3, "learning_rate": 0.05})

        result = run_baseline(
            series,
            model=model,
            initial_train_size=initial_train_size,
            train_fraction=train_fraction if initial_train_size is None else None,
            n_lags=n_lags,
            season_length=season_length,
            **kwargs,
        )
    except Exception as exc:
        status = "failed"
        error = f"{type(exc).__name__}: {exc}"

    runtime = time.perf_counter() - start
    row: Dict[str, Any] = {
        "dataset": dataset_name,
        "dataset_type": "real",
        "model": model,
        "source": "baseline_runner",
        "n_obs": len(series),
        "n_lags": n_lags,
        "season_length": season_length,
        "train_fraction": train_fraction,
        "initial_train_size": initial_train_size,
        "runtime_seconds": runtime,
        "status": status,
        "error": error,
    }

    pred_df = None
    if result is not None:
        row.update(result.metrics)
        row["failed_steps"] = len(result.failed_steps)
        row["n_test"] = len(result.y_true)

        pred_df = result.to_frame()
        for key, value in row.items():
            if key not in result.metrics:
                pred_df[key] = value

    return row, pred_df


def objective_for_protocol(protocol: str, objective: str) -> str:
    """Resolve NFPSO objective."""

    if objective != "auto":
        return objective
    if protocol == "legacy_intent":
        return "error_std"
    return "composite"


def model_name_for_protocol(protocol: str) -> str:
    """Map NFPSO protocol to table model name."""

    if protocol == "legacy_intent":
        return "legacy_nfpso"
    if protocol == "research_baseline":
        return "projected_constricted_nfpso"
    return protocol


def flatten(prefix: str, values: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """Flatten dictionary with prefix."""

    if not values:
        return {}
    return {
        f"{prefix}_{key}": value
        for key, value in values.items()
        if isinstance(value, (int, float, str, bool)) or value is None
    }


def copy_test_metrics(summary: Dict[str, Any]) -> Dict[str, Any]:
    """Copy test metrics to unprefixed columns."""

    metrics = summary.get("test_metrics") or {}
    return {
        key: value
        for key, value in metrics.items()
        if isinstance(value, (int, float)) or value is None
    }


def make_experiment_config(
    csv_path: Path,
    output_dir: Path,
    protocol: str,
    objective: str,
    radius: float,
    seed: int,
    particles: int,
    iterations: int,
    config: Dict[str, Any],
    n_lags: int,
    train_fraction: float,
) -> ExperimentConfig:
    """Create ExperimentConfig for an NFPSO real-data run."""

    nfpso_cfg = config.get("nfpso", {})

    return ExperimentConfig(
        csv_path=str(csv_path),
        output_dir=str(output_dir),
        n_lags=int(n_lags),
        train_fraction=float(train_fraction),
        sc_radius=float(radius),
        protocol=protocol,
        objective=objective,
        sensitivity_weight=float(nfpso_cfg.get("sensitivity_weight", 0.001)),
        validation_fraction=float(nfpso_cfg.get("validation_fraction", 0.20)),
        activation_floor=float(nfpso_cfg.get("activation_floor", 1e-4)),
        activation_penalty_weight=float(nfpso_cfg.get("activation_penalty_weight", 0.01)),
        seed=int(seed),
        iterations=int(iterations),
        particles=int(particles),
    )


def run_nfpso_model(
    csv_path: Path,
    output_root: Path,
    dataset_name: str,
    protocol: str,
    objective: str,
    radius: float,
    seed: int,
    particles: int,
    iterations: int,
    config: Dict[str, Any],
    n_lags: int,
    train_fraction: float,
) -> tuple[Dict[str, Any], Optional[pd.DataFrame]]:
    """Run one NFPSO model and return metrics row plus optional predictions."""

    model = model_name_for_protocol(protocol)
    run_name = f"{protocol}_obj{objective}_r{radius}_p{particles}_i{iterations}_seed{seed}".replace(".", "p")
    run_dir = ensure_dir(output_root / "runs" / run_name)

    print(
        f"[NFPSO] dataset={dataset_name} model={model} protocol={protocol} "
        f"objective={objective} radius={radius} seed={seed}"
    )

    start = time.perf_counter()
    status = "ok"
    error = None
    summary: Optional[Dict[str, Any]] = None

    try:
        exp_cfg = make_experiment_config(
            csv_path=csv_path,
            output_dir=run_dir,
            protocol=protocol,
            objective=objective,
            radius=radius,
            seed=seed,
            particles=particles,
            iterations=iterations,
            config=config,
            n_lags=n_lags,
            train_fraction=train_fraction,
        )
        summary = run_experiment(exp_cfg)
    except Exception as exc:
        status = "failed"
        error = f"{type(exc).__name__}: {exc}"

    runtime = time.perf_counter() - start
    row: Dict[str, Any] = {
        "dataset": dataset_name,
        "dataset_type": "real",
        "model": model,
        "source": "nfpso_runner",
        "protocol": protocol,
        "objective": objective,
        "sc_radius": radius,
        "seed": seed,
        "particles": particles,
        "iterations": iterations,
        "n_lags": n_lags,
        "train_fraction": train_fraction,
        "runtime_seconds": runtime,
        "status": status,
        "error": error,
        "run_dir": relpath(run_dir),
    }

    if summary is not None:
        row.update(copy_test_metrics(summary))
        row.update(flatten("initial_test", summary.get("initial_test_metrics")))
        row.update(flatten("train", summary.get("train_metrics")))
        row.update(flatten("validation", summary.get("validation_metrics")))
        row.update(flatten("test", summary.get("test_metrics")))
        row.update(flatten("diagnostics", summary.get("diagnostics")))
        row.update(flatten("initial_diagnostics", summary.get("initial_diagnostics")))

    pred_df = None
    for pred_name in ["test_predictions.csv", "predictions.csv"]:
        pred_path = run_dir / pred_name
        if pred_path.exists():
            try:
                pred_df = pd.read_csv(pred_path)
                pred_df["dataset"] = dataset_name
                pred_df["dataset_type"] = "real"
                pred_df["model"] = model
                pred_df["source"] = "nfpso_runner"
                pred_df["protocol"] = protocol
                pred_df["prediction_source_file"] = relpath(pred_path)
            except Exception:
                pred_df = None
            break

    return row, pred_df


def import_existing_nfpso_metrics(
    metrics_path: Path,
    predictions_path: Path,
    dataset_name: str,
) -> tuple[List[Dict[str, Any]], List[pd.DataFrame]]:
    """Import existing NFPSO metrics and force a common dataset key."""

    rows: List[Dict[str, Any]] = []
    predictions: List[pd.DataFrame] = []

    if not metrics_path.exists():
        print(f"[SKIP] existing NFPSO metrics not found: {metrics_path}")
        return rows, predictions

    df = pd.read_csv(metrics_path)
    if df.empty:
        print(f"[SKIP] existing NFPSO metrics are empty: {metrics_path}")
        return rows, predictions

    if "status" in df.columns:
        df = df[df["status"].fillna("ok").astype(str).str.lower().eq("ok")].copy()

    if df.empty:
        print("[SKIP] existing NFPSO metrics contain no successful rows.")
        return rows, predictions

    df["dataset"] = dataset_name
    df["dataset_type"] = "real"
    df["source"] = "imported_existing_nfpso"
    df["imported_from"] = relpath(metrics_path)

    print(f"[IMPORT] NFPSO metrics rows={len(df)} from {metrics_path}")
    rows = df.to_dict(orient="records")

    if predictions_path.exists():
        try:
            pred = pd.read_csv(predictions_path)
            if not pred.empty:
                pred["dataset"] = dataset_name
                pred["dataset_type"] = "real"
                pred["source"] = "imported_existing_nfpso"
                pred["prediction_source_file"] = relpath(predictions_path)
                predictions.append(pred)
        except Exception as exc:
            print(f"[WARN] failed to import NFPSO predictions: {type(exc).__name__}: {exc}")

    return rows, predictions


def resolve_nfpso_settings(
    config: Dict[str, Any],
    quick: bool,
    cli_protocols: Optional[List[str]],
    cli_radii: Optional[List[float]],
    cli_seeds: Optional[List[int]],
    cli_particles: Optional[int],
    cli_iterations: Optional[int],
) -> tuple[List[str], List[float], List[int], int, int]:
    """Resolve NFPSO experiment settings."""

    protocols = cli_protocols or ["research_baseline"]
    valid = {"legacy_intent", "research_baseline"}
    invalid = [p for p in protocols if p not in valid]
    if invalid:
        raise ValueError(f"Invalid protocols: {invalid}")

    radii = (
        cli_radii
        or config.get("radius_sweep", {}).get("radii")
        or config.get("stability_sweep", {}).get("radii")
        or config.get("nfpso", {}).get("radii")
        or [0.55]
    )
    seeds = cli_seeds or config.get("seed_study", {}).get("seeds", config.get("random_seeds", [1]))

    nfpso_cfg = config.get("nfpso", {})
    particles = int(cli_particles if cli_particles is not None else nfpso_cfg.get("particles", 12))
    iterations = int(cli_iterations if cli_iterations is not None else nfpso_cfg.get("iterations", 40))

    if quick:
        protocols = ["research_baseline"] if "research_baseline" in protocols else protocols[:1]
        radii = [0.55 if 0.55 in [float(r) for r in radii] else float(radii[0])]
        seeds = [int(seeds[0])] if seeds else [1]
        particles = min(particles, 5)
        iterations = min(iterations, 5)

    return (
        [str(p) for p in protocols],
        [float(r) for r in radii],
        [int(s) for s in seeds],
        particles,
        iterations,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Run real-data baselines and unify them with NFPSO metrics.")
    parser.add_argument("--config", default=str(DEFAULT_CONFIG), help="Experiment config JSON.")
    parser.add_argument("--csv", default=str(DEFAULT_CSV), help="Local private real-data CSV.")
    parser.add_argument("--dataset-name", default="yemen_tax_revenue", help="Unified dataset key for comparisons.")
    parser.add_argument("--date-column", default=None, help="Optional date column name.")
    parser.add_argument("--value-column", default=None, help="Optional target value column name.")
    parser.add_argument("--output-dir", default=None, help="Override output directory.")
    parser.add_argument("--models", default=None, help="Comma-separated baseline models.")
    parser.add_argument("--nfpso-source", choices=["auto", "existing", "run", "skip"], default="auto")
    parser.add_argument("--nfpso-metrics", default=str(DEFAULT_NFPSO_METRICS), help="Existing NFPSO metrics CSV.")
    parser.add_argument("--nfpso-predictions", default=str(DEFAULT_NFPSO_PREDICTIONS), help="Existing NFPSO predictions CSV.")
    parser.add_argument("--protocols", default=None, help="NFPSO protocols when --nfpso-source run.")
    parser.add_argument("--objective", default="auto", choices=["auto", "error_std", "rmse", "composite"])
    parser.add_argument("--radii", default=None, help="Comma-separated NFPSO radii when running NFPSO.")
    parser.add_argument("--seeds", default=None, help="Comma-separated NFPSO seeds when running NFPSO.")
    parser.add_argument("--particles", type=int, default=None, help="Override NFPSO particles when running NFPSO.")
    parser.add_argument("--iterations", type=int, default=None, help="Override NFPSO iterations when running NFPSO.")
    parser.add_argument("--n-lags", type=int, default=None, help="Lag count for baselines and NFPSO.")
    parser.add_argument("--season-length", type=int, default=12, help="Season length for seasonal baselines.")
    parser.add_argument("--train-fraction", type=float, default=0.85, help="Chronological train fraction.")
    parser.add_argument("--initial-train-size", type=int, default=None, help="Optional fixed initial train size.")
    parser.add_argument("--quick", action="store_true", help="Light smoke test.")
    args = parser.parse_args()

    config = load_json(Path(args.config))
    csv_path = Path(args.csv)

    try:
        data = load_real_series(
            csv_path=csv_path,
            value_column=args.value_column,
            date_column=args.date_column,
        )
    except Exception as exc:
        print(f"[ERROR] failed to load real data: {type(exc).__name__}: {exc}")
        return 2

    series = data["value"].to_numpy(dtype=float)
    n_lags = int(args.n_lags if args.n_lags is not None else config.get("nfpso", {}).get("default_n_lags", 5))
    baselines = resolve_baselines(config, parse_csv_list(args.models), quick=args.quick)

    output_root = Path(args.output_dir or config.get("output_dir", "outputs/q1_minimal"))
    output_root = ensure_dir(ROOT / output_root / "real_data_benchmarks")

    print(f"[INFO] csv={csv_path}")
    print(f"[INFO] n_obs={len(series)} value_min={float(data['value'].min())} value_max={float(data['value'].max())}")
    print(f"[INFO] output_root={output_root}")
    print(f"[INFO] dataset_name={args.dataset_name}")
    print(f"[INFO] baselines={baselines}")
    print(f"[INFO] n_lags={n_lags} season_length={args.season_length} train_fraction={args.train_fraction}")

    metric_rows: List[Dict[str, Any]] = []
    prediction_frames: List[pd.DataFrame] = []

    for model in baselines:
        row, pred = run_baseline_model(
            series=series,
            dataset_name=args.dataset_name,
            model=model,
            n_lags=n_lags,
            season_length=int(args.season_length),
            train_fraction=float(args.train_fraction),
            initial_train_size=args.initial_train_size,
        )
        metric_rows.append(row)
        if pred is not None:
            prediction_frames.append(pred)

    nfpso_source = args.nfpso_source
    if nfpso_source == "auto":
        nfpso_source = "existing" if Path(args.nfpso_metrics).exists() else "run"

    if nfpso_source == "existing":
        rows, preds = import_existing_nfpso_metrics(
            metrics_path=Path(args.nfpso_metrics),
            predictions_path=Path(args.nfpso_predictions),
            dataset_name=args.dataset_name,
        )
        metric_rows.extend(rows)
        prediction_frames.extend(preds)
    elif nfpso_source == "run":
        protocols, radii, seeds, particles, iterations = resolve_nfpso_settings(
            config=config,
            quick=args.quick,
            cli_protocols=parse_csv_list(args.protocols),
            cli_radii=parse_float_list(args.radii),
            cli_seeds=parse_int_list(args.seeds),
            cli_particles=args.particles,
            cli_iterations=args.iterations,
        )
        print(
            f"[INFO] running NFPSO protocols={protocols} radii={radii} "
            f"seeds={seeds} particles={particles} iterations={iterations}"
        )
        for protocol in protocols:
            objective = objective_for_protocol(protocol, args.objective)
            for radius in radii:
                for seed in seeds:
                    row, pred = run_nfpso_model(
                        csv_path=csv_path,
                        output_root=output_root,
                        dataset_name=args.dataset_name,
                        protocol=protocol,
                        objective=objective,
                        radius=float(radius),
                        seed=int(seed),
                        particles=particles,
                        iterations=iterations,
                        config=config,
                        n_lags=n_lags,
                        train_fraction=float(args.train_fraction),
                    )
                    metric_rows.append(row)
                    if pred is not None:
                        prediction_frames.append(pred)
    else:
        print("[INFO] skipping NFPSO metrics by request.")

    metrics_df = pd.DataFrame(metric_rows)
    metrics_path = output_root / "metrics.csv"
    metrics_df.to_csv(metrics_path, index=False, encoding="utf-8-sig")

    predictions_path = output_root / "predictions.csv"
    if prediction_frames:
        pd.concat(prediction_frames, ignore_index=True, sort=False).to_csv(
            predictions_path,
            index=False,
            encoding="utf-8-sig",
        )
    else:
        pd.DataFrame().to_csv(predictions_path, index=False, encoding="utf-8-sig")

    manifest_path = output_root / "manifest.csv"
    manifest_cols = [
        c for c in [
            "dataset",
            "model",
            "source",
            "protocol",
            "objective",
            "sc_radius",
            "seed",
            "particles",
            "iterations",
            "n_obs",
            "n_lags",
            "season_length",
            "train_fraction",
            "runtime_seconds",
            "status",
            "error",
            "run_dir",
            "imported_from",
        ]
        if c in metrics_df.columns
    ]
    metrics_df[manifest_cols].to_csv(manifest_path, index=False, encoding="utf-8-sig")

    print(f"[DONE] metrics: {metrics_path}")
    print(f"[DONE] predictions: {predictions_path}")
    print(f"[DONE] manifest: {manifest_path}")

